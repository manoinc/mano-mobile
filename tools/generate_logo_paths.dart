// Generates `packages/mano_ui/lib/src/brand/mano_logo_paths.g.dart` from the
// SVGs in `tools/brand/`.
//
// Why generate Dart rather than ship the SVGs and a renderer:
//
//   - `mano_ui` declares Flutter and nothing else. A logo that is Dart source
//     keeps that true; `flutter_svg` would not.
//   - The artwork is potrace output, so both files carry a great deal of dead
//     padding -- the monogram's glyph fills 986 x 599 of an 1800 x 1818 canvas.
//     Anything laying it out with `BoxFit.contain` would render it small and
//     off-centre. Generating bakes the tight box in, so `ManoLogo` is exact at
//     any size.
//   - The wordmark's contours turn out to be one per letter, which is what
//     makes the opening animation's staggered reveal possible at all. That is
//     only reachable by looking inside the file.
//
// Run from the repository root after replacing a file in `tools/brand/`:
//
//     dart tools/generate_logo_paths.dart
//
// The paths are still called "provisional" upstream. Re-running is the whole
// migration when they stop being.

import 'dart:io';
import 'dart:math' as math;

void main(List<String> args) {
  final root = Directory.current.path;
  final wordmark = _Glyphs.parse(File('$root/tools/brand/mano-wordmark.svg'));
  final monogram = _Glyphs.parse(File('$root/tools/brand/mano-monogram.svg'));

  if (wordmark.glyphs.length != 4) {
    stderr.writeln(
      'Expected the wordmark to resolve to 4 glyphs (m a n o), got '
      '${wordmark.glyphs.length}. The artwork changed shape; teach the '
      'generator the new grouping before trusting its output.',
    );
    exitCode = 1;
    return;
  }
  if (monogram.glyphs.length != 1) {
    stderr.writeln(
      'Expected the monogram to resolve to 1 glyph, got '
      '${monogram.glyphs.length}.',
    );
    exitCode = 1;
    return;
  }

  final out = File('$root/packages/mano_ui/lib/src/brand/mano_logo_paths.g.dart');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync(_emit(wordmark, monogram));
  stdout.writeln('wrote ${out.path}');
  stdout.writeln(
    '  wordmark ${wordmark.width.toStringAsFixed(1)} x '
    '${wordmark.height.toStringAsFixed(1)}  '
    '(${wordmark.glyphs.length} glyphs: '
    '${wordmark.glyphs.map((g) => g.contours.length).join('+')} contours)',
  );
  stdout.writeln(
    '  monogram ${monogram.width.toStringAsFixed(1)} x '
    '${monogram.height.toStringAsFixed(1)}',
  );
}

// ── Emitting ────────────────────────────────────────────────────────────────

const _letters = ['m', 'a', 'n', 'o'];

String _emit(_Glyphs wordmark, _Glyphs monogram) {
  final b = StringBuffer()
    ..writeln('// GENERATED BY tools/generate_logo_paths.dart -- DO NOT EDIT.')
    ..writeln('//')
    ..writeln('// Source: tools/brand/mano-wordmark.svg, tools/brand/mano-monogram.svg')
    ..writeln('// Re-run `dart tools/generate_logo_paths.dart` after changing either.')
    ..writeln('//')
    ..writeln('// Coordinates are normalised to each lockup\'s tight bounding box, so the')
    ..writeln('// origin is the first inked pixel and the extent is the last. Scale by')
    ..writeln('// `size / kManoWordmarkSize` to draw.')
    ..writeln()
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln('/// The wordmark\'s tight bounds, in its own coordinate space.')
    ..writeln('const Size kManoWordmarkSize = '
        'Size(${_n(wordmark.width)}, ${_n(wordmark.height)});')
    ..writeln()
    ..writeln('/// The standalone monogram\'s tight bounds, in its own coordinate space.')
    ..writeln('///')
    ..writeln('/// A different drawing from the wordmark\'s `m` -- ${monogram.glyphs.single.coordCount} coordinates')
    ..writeln('/// against ${wordmark.glyphs[0].coordCount} -- so the two cannot be morphed segment to')
    ..writeln('/// segment. Their proportions agree to within a fifth of a percent, though')
    ..writeln('/// (aspect ${(monogram.width / monogram.height).toStringAsFixed(3)} against '
        '${(wordmark.glyphs[0].width / wordmark.glyphs[0].height).toStringAsFixed(3)}), so they fill the same box: '
        'scaling one to')
    ..writeln('/// the other\'s bounds and cross-fading reads as a single mark. That is what')
    ..writeln('/// lets the native splash hand over to the opening animation without a seam.')
    ..writeln('const Size kManoMonogramSize = '
        'Size(${_n(monogram.width)}, ${_n(monogram.height)});')
    ..writeln();

  for (var i = 0; i < wordmark.glyphs.length; i++) {
    final g = wordmark.glyphs[i];
    b
      ..writeln('/// The wordmark\'s `${_letters[i]}`, in wordmark coordinates.')
      ..writeln('///')
      ..writeln('/// Occupies x ${_n(g.left)}..${_n(g.right)} of '
          '${_n(wordmark.width)}.')
      ..writeln('Path manoWordmark${_letters[i].toUpperCase()}() => '
          '${_pathExpr(g)};')
      ..writeln();
  }

  b
    ..writeln('/// The wordmark\'s glyphs, left to right: m, a, n, o.')
    ..writeln('///')
    ..writeln('/// The opening animation leans on this order; it is the reason the')
    ..writeln('/// letters can arrive one at a time without slicing the artwork up.')
    ..writeln('final List<Path Function()> kManoWordmarkGlyphs = '
        'List.unmodifiable(<Path Function()>[')
    ..writeln(_letters.map((l) => '  manoWordmark${l.toUpperCase()},').join('\n'))
    ..writeln(']);')
    ..writeln()
    ..writeln('/// The horizontal extent of each wordmark glyph, in wordmark coordinates.')
    ..writeln('const List<(double, double)> kManoWordmarkGlyphExtents = '
        '<(double, double)>[')
    ..writeln(wordmark.glyphs
        .map((g) => '  (${_n(g.left)}, ${_n(g.right)}),')
        .join('\n'))
    ..writeln('];')
    ..writeln()
    ..writeln('/// The whole wordmark as one path.')
    ..writeln('Path manoWordmark() => Path()')
    ..writeln(_letters
        .map((l) => '  ..addPath(manoWordmark${l.toUpperCase()}(), Offset.zero)')
        .join('\n'))
    ..writeln('  ;')
    ..writeln()
    ..writeln('/// The standalone monogram, in monogram coordinates.')
    ..writeln('Path manoMonogram() => ${_pathExpr(monogram.glyphs.single)};')
    ..writeln();

  return b.toString();
}

String _pathExpr(_Glyph g) {
  final b = StringBuffer('Path()');
  for (final contour in g.contours) {
    b.write('\n    ..moveTo(${_n(contour.start.x)}, ${_n(contour.start.y)})');
    for (final s in contour.segments) {
      if (s is _Line) {
        b.write('\n    ..lineTo(${_n(s.to.x)}, ${_n(s.to.y)})');
      } else if (s is _Cubic) {
        b.write('\n    ..cubicTo(${_n(s.c1.x)}, ${_n(s.c1.y)}, '
            '${_n(s.c2.x)}, ${_n(s.c2.y)}, ${_n(s.to.x)}, ${_n(s.to.y)})');
      }
    }
    b.write('\n    ..close()');
  }
  return b.toString();
}

/// Three decimals is finer than a physical pixel at any size the logo is drawn,
/// and keeps the generated file readable.
String _n(double v) {
  final r = (v * 1000).round() / 1000;
  final s = r.toStringAsFixed(3).replaceFirst(RegExp(r'0+$'), '');
  return s.endsWith('.') ? '${s}0' : s;
}

// ── Geometry ────────────────────────────────────────────────────────────────

class _P {
  const _P(this.x, this.y);
  final double x;
  final double y;
  _P operator +(_P o) => _P(x + o.x, y + o.y);
}

sealed class _Seg {
  _P get to;
}

class _Line implements _Seg {
  _Line(this.to);
  @override
  final _P to;
}

class _Cubic implements _Seg {
  _Cubic(this.c1, this.c2, this.to);
  final _P c1;
  final _P c2;
  @override
  final _P to;
}

class _Contour {
  _Contour(this.start);
  final _P start;
  final List<_Seg> segments = [];

  _Contour map(_P Function(_P) f) {
    final out = _Contour(f(start));
    for (final s in segments) {
      out.segments.add(switch (s) {
        _Line() => _Line(f(s.to)),
        _Cubic() => _Cubic(f(s.c1), f(s.c2), f(s.to)),
      });
    }
    return out;
  }

  /// Exact bounds, solving each cubic for its turning points rather than
  /// settling for the control hull -- the hull would leave the logo sitting a
  /// percent or so inside whatever box it is given, which is visible when it
  /// has to line up with a native splash drawn from the same artwork.
  (double, double, double, double) get bounds {
    var minX = start.x, maxX = start.x, minY = start.y, maxY = start.y;
    void hitX(double x) {
      minX = math.min(minX, x);
      maxX = math.max(maxX, x);
    }

    void hitY(double y) {
      minY = math.min(minY, y);
      maxY = math.max(maxY, y);
    }

    var cur = start;
    for (final s in segments) {
      hitX(s.to.x);
      hitY(s.to.y);
      if (s case _Cubic(:final c1, :final c2, :final to)) {
        for (final t in _cubicExtrema(cur.x, c1.x, c2.x, to.x)) {
          hitX(_cubicAt(cur.x, c1.x, c2.x, to.x, t));
        }
        for (final t in _cubicExtrema(cur.y, c1.y, c2.y, to.y)) {
          hitY(_cubicAt(cur.y, c1.y, c2.y, to.y, t));
        }
      }
      cur = s.to;
    }
    return (minX, minY, maxX, maxY);
  }
}

double _cubicAt(double p0, double p1, double p2, double p3, double t) {
  final u = 1 - t;
  return u * u * u * p0 +
      3 * u * u * t * p1 +
      3 * u * t * t * p2 +
      t * t * t * p3;
}

List<double> _cubicExtrema(double p0, double p1, double p2, double p3) {
  final a = 3 * (-p0 + 3 * p1 - 3 * p2 + p3);
  final b = 6 * (p0 - 2 * p1 + p2);
  final c = 3 * (p1 - p0);
  final out = <double>[];
  void keep(double t) {
    if (t > 0 && t < 1) out.add(t);
  }

  if (a.abs() < 1e-12) {
    if (b.abs() > 1e-12) keep(-c / b);
    return out;
  }
  final disc = b * b - 4 * a * c;
  if (disc < 0) return out;
  final root = math.sqrt(disc);
  keep((-b + root) / (2 * a));
  keep((-b - root) / (2 * a));
  return out;
}

class _Glyph {
  _Glyph(this.contours);
  final List<_Contour> contours;

  (double, double, double, double) get bounds {
    var b = contours.first.bounds;
    for (final c in contours.skip(1)) {
      final o = c.bounds;
      b = (math.min(b.$1, o.$1), math.min(b.$2, o.$2),
           math.max(b.$3, o.$3), math.max(b.$4, o.$4));
    }
    return b;
  }

  double get left => bounds.$1;
  double get right => bounds.$3;
  double get width => bounds.$3 - bounds.$1;
  double get height => bounds.$4 - bounds.$2;

  _Glyph map(_P Function(_P) f) => _Glyph([for (final c in contours) c.map(f)]);

  /// How many numbers the glyph costs to describe. Only used to say, in the
  /// generated doc, how far the monogram and the wordmark's `m` really are
  /// apart -- their bounding boxes agree closely enough to be misleading.
  int get coordCount => contours.fold(
        0,
        (n, c) => n + 2 + c.segments.fold(0, (m, s) => m + (s is _Cubic ? 6 : 2)),
      );
}

class _Glyphs {
  _Glyphs(this.glyphs, this.width, this.height);
  final List<_Glyph> glyphs;
  final double width;
  final double height;

  static _Glyphs parse(File file) {
    final svg = file.readAsStringSync();

    final viewBox = RegExp(r'viewBox="([\d.\s-]+)"').firstMatch(svg);
    if (viewBox == null) throw StateError('${file.path}: no viewBox');
    final vb = viewBox
        .group(1)!
        .trim()
        .split(RegExp(r'[\s,]+'))
        .map(double.parse)
        .toList();

    // potrace emits a single `translate(tx,ty) scale(sx,sy)` wrapper. The
    // negative y scale is what flips its bottom-up tracing space into SVG's
    // top-down one; because it is affine, control points ride along and the
    // curves keep their shape.
    final tr = RegExp(
      r'transform="translate\(([-\d.]+),([-\d.]+)\)\s*scale\(([-\d.]+),([-\d.]+)\)"',
    ).firstMatch(svg);
    if (tr == null) throw StateError('${file.path}: unexpected transform');
    final tx = double.parse(tr.group(1)!);
    final ty = double.parse(tr.group(2)!);
    final sx = double.parse(tr.group(3)!);
    final sy = double.parse(tr.group(4)!);
    _P place(_P p) => _P(tx + sx * p.x, ty + sy * p.y);

    // One `<path>` element per contour group as potrace wrote it; a letter with
    // a counter (a, o) arrives as one element holding two contours.
    final elements = RegExp(r'\sd="([^"]+)"')
        .allMatches(svg)
        .map((m) => _parsePath(m.group(1)!).map(place))
        .toList();
    if (elements.isEmpty) throw StateError('${file.path}: no paths');

    // Group by horizontal overlap rather than by hand. The `m` and its centre
    // tab are separate elements that overlap; the four letters do not touch.
    // That makes the grouping a property of the artwork instead of a constant
    // in here that would quietly rot the next time the logo is redrawn.
    final glyphs = _groupByOverlap(elements)
      ..sort((a, b) => a.left.compareTo(b.left));

    var b = glyphs.first.bounds;
    for (final g in glyphs.skip(1)) {
      final o = g.bounds;
      b = (math.min(b.$1, o.$1), math.min(b.$2, o.$2),
           math.max(b.$3, o.$3), math.max(b.$4, o.$4));
    }
    final (minX, minY, maxX, maxY) = b;
    if (vb.length == 4) {
      // Sanity only: the declared canvas must contain the ink.
      assert(minX >= -1 && minY >= -1 && maxX <= vb[2] + 1 && maxY <= vb[3] + 1);
    }

    _P origin(_P p) => _P(p.x - minX, p.y - minY);
    return _Glyphs(
      [for (final g in glyphs) g.map(origin)],
      maxX - minX,
      maxY - minY,
    );
  }
}

List<_Glyph> _groupByOverlap(List<_Glyph> elements) {
  final groups = <List<_Glyph>>[];
  for (final e in elements) {
    final hit = groups.indexWhere(
      (g) => g.any((o) => e.left < o.right && o.left < e.right),
    );
    if (hit == -1) {
      groups.add([e]);
    } else {
      groups[hit].add(e);
    }
  }
  return [
    for (final g in groups) _Glyph([for (final e in g) ...e.contours]),
  ];
}

// ── The potrace path subset: M, m, c, l, z ──────────────────────────────────

_Glyph _parsePath(String d) {
  final tokens = RegExp(r'([MmCcLlZzHhVvSsQqTtAa])|(-?\d*\.?\d+(?:[eE][-+]?\d+)?)')
      .allMatches(d)
      .map((m) => m.group(1) ?? m.group(2)!)
      .toList();

  final contours = <_Contour>[];
  _Contour? contour;
  var cur = const _P(0, 0);
  var subpathStart = const _P(0, 0);
  String? cmd;
  var i = 0;

  double num() => double.parse(tokens[i++]);

  while (i < tokens.length) {
    final t = tokens[i];
    if (RegExp(r'^[A-Za-z]$').hasMatch(t)) {
      cmd = t;
      i++;
      if (cmd == 'z' || cmd == 'Z') {
        // SVG leaves the pen at the subpath's start after a close.
        cur = subpathStart;
        contour = null;
        continue;
      }
    }
    switch (cmd) {
      case 'M':
      case 'm':
        final p = _P(num(), num());
        cur = cmd == 'M' ? p : cur + p;
        subpathStart = cur;
        contour = _Contour(cur);
        contours.add(contour);
        // A repeated coordinate pair after a moveto is an implicit lineto.
        cmd = cmd == 'M' ? 'L' : 'l';
      case 'L':
      case 'l':
        final p = _P(num(), num());
        cur = cmd == 'L' ? p : cur + p;
        contour!.segments.add(_Line(cur));
      case 'C':
      case 'c':
        final rel = cmd == 'c';
        final c1 = _P(num(), num());
        final c2 = _P(num(), num());
        final to = _P(num(), num());
        final a1 = rel ? cur + c1 : c1;
        final a2 = rel ? cur + c2 : c2;
        final a3 = rel ? cur + to : to;
        contour!.segments.add(_Cubic(a1, a2, a3));
        cur = a3;
      default:
        throw StateError('unsupported path command "$cmd" -- the artwork is no '
            'longer plain potrace output, so the generator needs teaching');
    }
  }
  return _Glyph(contours);
}
